// Snapshot baseline of test/topology.html (see CONTRIBUTING.md, "Topology test and drawing snapshot").
//
//   node scripts/topology-snapshot.mjs --update          writes test/topology-snapshot.js from the current card
//   node scripts/topology-snapshot.mjs --out before.json  writes the full descriptions of every case
//   node scripts/topology-snapshot.mjs --diff before.json after.json
//                                                        lists the cases that differ and their first differing lines
//
// Runs in Chromium; HFC_BROWSER=firefox runs --out in Firefox to compare the two browsers.
// A change that must not alter the drawing (a refactor) leaves the baseline as it is. A change that alters the drawing on
// purpose updates the baseline in the same pull request; --out before and after the change shows what moved.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const root = resolve(import.meta.dirname, '..');

const diff = (a, b) => {
  const before = JSON.parse(readFileSync(a, 'utf8')); const after = JSON.parse(readFileSync(b, 'utf8'));
  let changed = 0;
  for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
    const x = before[key]; const y = after[key];
    if (!x || !y) { changed++; console.log(`${key}: only in ${x ? a : b}`); continue; }
    if (x.h === y.h) continue;
    changed++;
    for (const part of ['geo', 'state']) {
      const n = x[part].findIndex((line, k) => line !== y[part][k]);
      if (n < 0 && x[part].length === y[part].length) continue;
      console.log(`${key} – ${part}:\n  - ${x[part][n] ?? '(none)'}\n  + ${y[part][n] ?? '(none)'}`);
    }
  }
  console.log(changed ? `${changed} cases differ` : 'no differences');
  process.exitCode = changed ? 1 : 0;
};

const run = async () => {
  const playwright = await import('playwright');
  const firefox = process.env.HFC_BROWSER === 'firefox';
  const browser = firefox ? await playwright.firefox.launch() : await playwright.chromium.launch({ executablePath: process.env.HFC_CHROMIUM || undefined });
  try {
    // Same browser locale as the Playwright tests, so the baseline does not depend on the system language.
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, locale: 'en-US' });
    await page.goto(`${pathToFileURL(resolve(root, 'test/topology.html')).href}?dump`);
    await page.waitForFunction(() => ['DUMPED', 'FAIL'].includes(document.getElementById('result').textContent), null, { timeout: 600_000 });
    if ((await page.textContent('#result')) !== 'DUMPED') throw new Error(await page.textContent('#log'));
    return JSON.parse(await page.textContent('#dump'));
  } finally {
    await browser.close();
  }
};

if (args[0] === '--diff' && args.length === 3) diff(args[1], args[2]);
else if (args[0] === '--out' && args.length === 2) {
  const cases = await run();
  writeFileSync(args[1], JSON.stringify(cases, null, 1));
  console.log(`${Object.keys(cases).length} cases written to ${args[1]}`);
} else if (args[0] === '--update' && args.length === 1) {
  const cases = await run();
  const lines = Object.entries(cases).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value.h)},`);
  writeFileSync(resolve(root, 'test/topology-snapshot.js'), `// Generated by \`node scripts/topology-snapshot.mjs --update\`: fingerprints (geometry, state) of every case in test/topology.html.\nwindow.HFC_TOPOLOGY_SNAPSHOT = {\n${lines.join('\n')}\n};\n`);
  console.log(`${lines.length} cases written to test/topology-snapshot.js`);
} else {
  console.error('usage: topology-snapshot.mjs --update | --out <file> | --diff <before> <after>');
  process.exitCode = 2;
}
